/// Season of a month (Japan): 3–5 spring, 6–8 summer, 9–11 autumn, else
/// winter.
String seasonOf(int month) => switch (month) {
  3 || 4 || 5 => 'spring',
  6 || 7 || 8 => 'summer',
  9 || 10 || 11 => 'autumn',
  _ => 'winter',
};
