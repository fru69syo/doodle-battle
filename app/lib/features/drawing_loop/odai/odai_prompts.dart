/// A Japanese event shown on its days (local date, inclusive window).
class OdaiEvent {
  const OdaiEvent({
    required this.id,
    required this.month,
    required this.fromDay,
    required this.toDay,
    required this.prompts,
  });

  final String id;
  final int month;
  final int fromDay;
  final int toDay;
  final List<String> prompts;

  bool covers(int month, int day) =>
      month == this.month && day >= fromDay && day <= toDay;
}

