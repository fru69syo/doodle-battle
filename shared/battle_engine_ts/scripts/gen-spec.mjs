// Embeds shared/battle_spec/battle_spec.json into src/generated/specData.ts so
// the package works from any bundler / module system without file I/O.
// Usage: npm run gen            (write)
//        node scripts/gen-spec.mjs --check   (exit 1 if out of date)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const specPath = join(here, '..', '..', 'battle_spec', 'battle_spec.json');
const outPath = join(here, '..', 'src', 'generated', 'specData.ts');

const json = JSON.parse(readFileSync(specPath, 'utf8'));
const out =
  '// GENERATED by scripts/gen-spec.mjs from shared/battle_spec/battle_spec.json.\n' +
  '// Do not edit. Run `npm run gen` after changing the spec.\n' +
  `export const SPEC_DATA: unknown = ${JSON.stringify(json, null, 2)};\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {}
  if (current !== out) {
    console.error('src/generated/specData.ts is out of date: run `npm run gen`');
    process.exit(1);
  }
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, out);
}
